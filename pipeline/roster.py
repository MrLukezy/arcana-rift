def build():
    combos = [(r, c) for r in RACES for c in CLASSES]
    rnd = random.Random(20261124)
    rnd.shuffle(combos)
    # 保证职业分布均匀：每个职业最多 6 人
    picked, per = [], {}
    for r, c in combos:
        if per.get(c[0], 0) >= 6:
            continue
        picked.append((r, c))
        per[c[0]] = per.get(c[0], 0) + 1
        if len(picked) == 100:
            break

    rarities = []
    for rank, n in RARITY_PLAN:
        rarities += [rank] * n
    rnd.shuffle(rarities)

    cards = []
    for i, ((rk, rn, rdesc, relem), (ck, cn, role, cloth, weapon)) in enumerate(picked):
        rarity = rarities[i]
        elem = relem if i % 3 else list(ELEM_STYLE)[i % len(ELEM_STYLE)]
        pal, fx, motif = ELEM_STYLE[elem]
        pose = POSE[i % len(POSE)]
        ep = EPITHET[elem][i % 3]
        name = f"{ep}{rn}{cn}"
        prompt = (
            f"高质量日系抽卡手游角色立绘：一位{rn}娘{cn}少女，{rdesc}，{pal}，{cloth}，"
            f"{weapon}，{pose}，{fx}。{FLOURISH[rarity]}。"
            "画面要有强烈的立体纵深：发丝与披风有明确的前后遮挡层次，清晰的边缘轮廓光，"
            "身体有透视收缩，脚下有淡淡的投影。"
            "全身像，竖版 3:4 构图，纯 #00FF00 纯绿幕背景（背景必须完全均匀的亮绿色，"
            "不要任何场景、地面、渐变、阴影或光斑落在背景上），主体轮廓清晰干净、无绿色溢出。"
            "精致二次元厚涂画风，超高清细节。画面上不要出现任何文字、水印、logo、边框。"
        )
        cards.append({
            "id": f"{i+1:03d}",
            "slug": f"{rk}-{ck}-{i+1:03d}",
            "name": name,
            "race": rn, "race_key": rk, "race_desc": rdesc,
            "cls": cn, "cls_key": ck, "role": role,
            "element": elem, "palette": pal, "motif": motif, "wpn": WPN[ck],
            "rarity": rarity,
            "prompt": prompt,
        })
    return cards


